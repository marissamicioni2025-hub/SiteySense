import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const origin=process.env.SITESENSE_URL||'http://127.0.0.1:3000';
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),...(process.env.CHROMIUM_NO_SANDBOX==='1'?{args:['--no-sandbox']}:{})});
try{
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 const page=await context.newPage();const errors=[];let analysisCalls=0;
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',request=>{if(new URL(request.url()).pathname.startsWith('/api/analyze'))analysisCalls++;});
 // No live model calls or credentials are needed by this smoke test.
 await page.route('**/api/status',route=>route.fulfill({json:{visionConfigured:false,model:'test',videoModel:'test'}}));
 await page.goto(origin);await page.getByText('Camera & checklists · no key needed',{exact:true}).waitFor();
 assert.equal(await page.locator('.observation').count(),0);await page.locator('#walkthrough summary').click();await page.click('[data-scenario="roof-edge"]');await page.locator('[data-scenario="roof-edge"][aria-pressed="true"]').waitFor();
 await page.locator('#briefing-text').filter({hasText:'suggests proximity'}).waitFor();
 await page.click('[data-scenario="poor-light"]');
 await page.locator('#briefing-text').filter({hasText:'No visual hazard assessment can be made'}).waitFor();
 assert.ok(!(await page.locator('#briefing-text').textContent()).includes('suggests proximity'));
 await page.click('[data-scenario="eye-unclear"]');
 await page.locator('#briefing-text').filter({hasText:'can’t verify eye protection'}).waitFor();
 await page.selectOption('#task','ladder');
 await page.locator('#briefing-text').filter({hasText:'Before ladder access'}).waitFor();
 await page.locator('#checklist input').first().check();
 const downloadReady=page.waitForEvent('download');await page.click('#download-report');
 const download=await downloadReady;const stream=await download.createReadStream();let json='';for await(const chunk of stream)json+=chunk;
 const report=JSON.parse(json);assert.equal(report.mode,'demo');assert.equal(report.scenarioId,'eye-unclear');
 assert.equal(report.task,'ladder');assert.equal(report.conditions.source,'SIMULATED');
 assert.doesNotMatch(json,/base64|GEMINI_API_KEY|inlineData|data:image/);
 await page.click('#mobile-reviews');await page.locator('.saved-review').waitFor();
 await page.getByRole('button',{name:'Close saved reviews'}).click();
 await page.setInputFiles('#upload',{name:'site.png',mimeType:'image/png',buffer:await page.screenshot()});
 assert.equal(await page.locator('.observation').count(),0);
 assert.equal(await page.locator('[data-scenario][aria-pressed="true"]').count(),0);
 assert.equal(await page.locator('#illustration').getAttribute('hidden'),'');
 await page.click('#analyze');await page.getByText(/Automatic analysis is unavailable here/).waitFor();
 assert.equal(analysisCalls,0);
 await page.evaluate(async()=>{await navigator.serviceWorker.ready;if(!navigator.serviceWorker.controller)await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true}));});
 await context.setOffline(true);await page.reload();
 await page.getByText(/Offline workspace ·/).waitFor();
 await page.locator('#walkthrough').evaluate(el=>el.open=true);await page.click('[data-scenario="eye-unclear"]');await page.selectOption('#task','ladder');
 await page.getByText('1 / 3 VERIFIED',{exact:true}).waitFor();
 await page.locator('#wind').fill('40');
 await page.locator('#briefing-text').filter({hasText:'Gusty conditions'}).waitFor();
 await page.click('#mobile-reviews');await page.locator('.saved-review').waitFor();
 await page.click('#clear-reviews');await page.locator('.empty-state').waitFor();
 await page.getByRole('button',{name:'Close saved reviews'}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const cached=await page.evaluate(async()=>{const keys=await caches.keys();const name=keys.find(k=>k.startsWith('sitesense-shell-'));if(!name)return [];const cache=await caches.open(name);return (await cache.keys()).map(request=>new URL(request.url).pathname);});
 assert.ok(cached.includes('/scenarios.js'));assert.ok(!cached.some(path=>path.startsWith('/api/')));
 await context.setOffline(false);await page.setViewportSize({width:1440,height:1100});
 await page.reload();await page.locator('.guidance-item').first().waitFor();
 await page.click('#install-app');await page.getByText('SiteySense on your device',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Close installation instructions'}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('Browser smoke passed: three demos, grounded briefings, task switching, upload isolation, no-key guidance, report privacy and persistence, offline rules, cache boundaries, mobile/desktop layout and install help.');
}finally{await browser.close();}
